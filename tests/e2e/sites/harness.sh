#!/usr/bin/env bash
#
# harness.sh — run the APVM site-deployment E2E harness (WordPress over SSH in Docker).
#
# Usage: harness.sh COMMAND
#   up               Build the target, start db + target, wait until healthy, write
#                    .state/{id_ed25519,known_hosts,ssh_config}, smoke-test SSH, then
#                    write .state/env.
#   down             Stop and remove the containers (all site state is discarded).
#   env              Print the shell exports tests use: eval "$(harness.sh env)".
#   ssh USER [CMD]   SSH into the target as USER (see README.md for the users).
#   reset [SITE...]  Restore sites (default: all) to their freshly installed state.
#   logs             Print the containers' logs.
#
# Environment: APVM_E2E_SSH_PORT (2722), APVM_E2E_HTTP_PORT (8722), and
# APVM_E2E_WORDPRESS_IMAGE to build on another wordpress image (e.g. another PHP).
# Each checkout gets its own compose project, so worktrees never touch each other's
# harness; two harnesses at once need different ports.
set -euo pipefail

# shellcheck source=lib/common.sh
. "$(CDPATH='' cd -- "$(dirname -- "$0")" >/dev/null && pwd)/lib/common.sh"

# usage — prints this file's header comment.
usage() {
	awk 'NR > 2 && /^#/ { sub(/^# ?/, ""); print; next } NR > 2 { exit }' "$0"
}

# ensure_client_key — creates the harness's passphrase-less SSH key once (and its public
# half again if it went missing).
ensure_client_key() {
	mkdir -p "$STATE_DIR"
	chmod 0700 "$STATE_DIR"
	[ -f "$KEY_FILE" ] || ssh-keygen -q -t ed25519 -N '' -C apvm-e2e-harness -f "$KEY_FILE"
	[ -f "$KEY_FILE.pub" ] || ssh-keygen -y -f "$KEY_FILE" >"$KEY_FILE.pub"
}

# write_known_hosts — pins the container's host keys, read straight from the container
# (no trust on first use).
write_known_hosts() {
	local keys
	keys=$(target_exec sh -c 'cat /etc/ssh/ssh_host_*_key.pub')
	printf '%s\n' "$keys" | awk -v host="$(known_hosts_name)" '{ print host, $1, $2 }' >"$KNOWN_HOSTS"
}

# write_ssh_config — writes one `apvm-e2e-<user>` host alias per login user.
write_ssh_config() {
	local user
	{
		echo "# Generated by harness.sh up. Usage: ssh -F $SSH_CONFIG apvm-e2e-deploy"
		for user in $LOGIN_USERS; do
			printf 'Host apvm-e2e-%s\n  User %s\n' "$user" "$user"
		done
		cat <<EOF
Host apvm-e2e-*
  HostName $SSH_HOST
  Port $SSH_PORT
  IdentityFile "$KEY_FILE"
  IdentitiesOnly yes
  UserKnownHostsFile "$KNOWN_HOSTS"
  StrictHostKeyChecking yes
  BatchMode yes
  ConnectTimeout 10
  LogLevel ERROR
EOF
	} >"$SSH_CONFIG"
}

# write_env_file — writes the exports printed by `harness.sh env`.
write_env_file() {
	cat >"$ENV_FILE" <<EOF
export APVM_E2E_SITES=1
export APVM_E2E_SSH_HOST=$SSH_HOST
export APVM_E2E_SSH_PORT=$SSH_PORT
export APVM_E2E_HTTP_PORT=$HTTP_PORT
export APVM_E2E_SSH_KEY=$(q "$KEY_FILE")
export APVM_E2E_KNOWN_HOSTS=$(q "$KNOWN_HOSTS")
export APVM_E2E_SSH_CONFIG=$(q "$SSH_CONFIG")
EOF
}

# refuse_while_verifying ACTION — stops ACTION while a verify.sh run uses the harness.
refuse_while_verifying() {
	local pid
	if pid=$(verify_running); then
		die "verify.sh (PID $pid) is using the harness; wait for it before you $1"
	fi
}

cmd_up() {
	local build_args=()
	check_state_path
	ensure_client_key
	APVM_E2E_AUTHORIZED_KEY=$(cat "$KEY_FILE.pub")
	export APVM_E2E_AUTHORIZED_KEY
	if [ -n "${APVM_E2E_WORDPRESS_IMAGE:-}" ]; then
		build_args=(--build-arg "WORDPRESS_IMAGE=$APVM_E2E_WORDPRESS_IMAGE")
	fi
	rm -f "$ENV_FILE"
	compose build ${build_args[@]+"${build_args[@]}"}
	compose up --detach --wait --wait-timeout 300
	write_known_hosts
	write_ssh_config
	[ "$(ssh_to deploy 'id -un')" = deploy ] || die "SSH smoke test as deploy failed"
	write_env_file
	echo "Harness ready: ssh -F $SSH_CONFIG apvm-e2e-deploy"
}

cmd_down() {
	refuse_while_verifying "stop it"
	rm -f "$ENV_FILE"
	compose down --volumes --remove-orphans
}

cmd_env() {
	[ -f "$ENV_FILE" ] || die "the harness is not up (run: $0 up)"
	cat "$ENV_FILE"
}

cmd_ssh() {
	[ $# -ge 1 ] || die "usage: $0 ssh USER [COMMAND...]"
	local user=$1
	shift
	exec ssh -F "$SSH_CONFIG" "apvm-e2e-$user" "$@"
}

cmd_reset() {
	refuse_while_verifying "reset it"
	target_exec apvm-e2e reset "$@"
}

main() {
	local command=${1:-}
	[ $# -gt 0 ] && shift
	case $command in
	up) cmd_up ;;
	down) cmd_down ;;
	env) cmd_env ;;
	ssh) cmd_ssh "$@" ;;
	reset) cmd_reset "$@" ;;
	logs) compose logs --no-color ;;
	-h | --help) usage ;;
	*)
		usage >&2
		exit 2
		;;
	esac
}

main "$@"

//! Self-update command implementation.
//!
//! Downloads the latest APVM release from GitHub, verifies the SHA-256
//! checksum, and atomically replaces the running binary.
//!
//! # Cross-platform binary replacement
//!
//! - **Unix (Linux / macOS):** The kernel tracks open files by inode, not path.
//!   `self-replace` places the new binary next to the current executable and
//!   performs an atomic `rename(2)`.
//!   Source: <https://man7.org/linux/man-pages/man2/rename.2.html>
//!
//! - **Windows:** A running `.exe` can be renamed but not deleted. `self-replace`
//!   renames the current binary aside, puts the new one in place, then spawns a
//!   helper process with `FILE_FLAG_DELETE_ON_CLOSE` to clean up after exit.
//!   Source: <https://docs.rs/self-replace/1/self_replace/#implementation>
//!
//! # Security
//!
//! - Binary integrity is verified with SHA-256 against the `checksums.txt`
//!   asset published alongside each release.
//! - All downloads are HTTPS-only (enforced by `reqwest` with `native-tls`).
//! - The repository owner/name is hardcoded — no user-controlled redirect.


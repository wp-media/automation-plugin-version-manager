/// Execute the update command.
///
/// # Steps
///
/// 1. Fetch the latest release from GitHub
/// 2. Parse and compare versions with `semver`
/// 3. Detect the correct artifact for this platform
/// 4. Download the binary and checksums
/// 5. Verify SHA-256 integrity
/// 6. Atomically replace the running binary via `self-replace`
///
/// # Errors
///
/// Returns `Error::Update` for all update-specific failures (network, checksum
/// mismatch, platform not supported, etc.). Other errors (`Error::GitHub`,
/// `Error::Io`) propagate from underlying operations.
pub async fn execute() -> Result<()> {
    info("Checking for updates...");

    // ── 1. Fetch latest release ──────────────────────────────────────────
    let github = make_github_client().await?;
    let release = github
        .get_latest_release(REPO_OWNER, REPO_NAME)
        .await?
        .ok_or_else(|| {
            Error::Update(format!(
                "No releases found for {REPO_OWNER}/{REPO_NAME}.\n\
                 This is unexpected — please report it at:\n\
                 https://github.com/{REPO_OWNER}/{REPO_NAME}/issues"
            ))
        })?;

    // ── 2. Parse and compare versions ────────────────────────────────────
    //
    // semver::Version::parse():
    //   https://docs.rs/semver/1/semver/struct.Version.html#method.parse
    // semver::Version implements Ord for correct SemVer comparison:
    //   https://docs.rs/semver/1/semver/struct.Version.html#total-ordering
    let current = semver::Version::parse(CURRENT_VERSION).map_err(|e| {
        Error::Update(format!(
            "Failed to parse current version '{CURRENT_VERSION}': {e}"
        ))
    })?;

    let latest_tag = extract_version_from_tag(&release.tag_name);
    let latest = semver::Version::parse(latest_tag).map_err(|e| {
        Error::Update(format!(
            "Failed to parse release version '{}' (from tag '{}'): {e}",
            latest_tag, release.tag_name
        ))
    })?;

    eprintln!();
    success(&format!("Current version: {current}"));
    success(&format!("Latest version:  {latest}"));

    if latest <= current {
        eprintln!();
        success(&format!("apvm {current} is already the latest version."));
        return Ok(());
    }

    // ── 3. Detect platform ───────────────────────────────────────────────
    let artifact = artifact_name()?;
    eprintln!();
    info(&format!("Downloading {artifact}..."));

    // ── 4. Download checksums + binary ───────────────────────────────────
    let checksums_asset = find_asset(&release, CHECKSUMS_FILENAME)?;
    let checksums_bytes = github
        .download_release_asset(REPO_OWNER, REPO_NAME, checksums_asset)
        .await
        .map_err(|e| Error::Update(format!("Failed to download checksums.txt: {e}")))?;
    let checksums_text = String::from_utf8(checksums_bytes)
        .map_err(|e| Error::Update(format!("checksums.txt contains invalid UTF-8: {e}")))?;

    let expected_hash = parse_checksum(&checksums_text, artifact)?;

    let binary_asset = find_asset(&release, artifact)?;
    let binary_bytes = github
        .download_release_asset(REPO_OWNER, REPO_NAME, binary_asset)
        .await
        .map_err(|e| Error::Update(format!("Failed to download {artifact}: {e}")))?;

    success(&format!(
        "Downloaded ({})",
        format_size(binary_bytes.len() as u64)
    ));

    // ── 5. Verify SHA-256 ────────────────────────────────────────────────
    //
    // sha2::Sha256 implements the Digest trait.
    // sha2 0.11 returns an Array newtype; format each byte as two hex digits.
    //   https://docs.rs/sha2/0.11/sha2/type.Sha256.html
    //   https://doc.rust-lang.org/std/fmt/trait.LowerHex.html (u8 impl)
    let hash_bytes = Sha256::digest(&binary_bytes);
    let actual_hash: String = hash_bytes.iter().map(|b| format!("{b:02x}")).collect();

    if actual_hash != expected_hash {
        error_msg("Checksum verification failed!");
        error_msg(&format!("  Expected: {expected_hash}"));
        error_msg(&format!("  Actual:   {actual_hash}"));
        return Err(Error::Update(
            "SHA-256 checksum mismatch — the download may be corrupted.\n\
             Please try again. If the problem persists, report it at:\n\
             https://github.com/wp-media/automation-plugin-version-manager/issues"
                .to_string(),
        ));
    }
    success("Checksum verified (SHA-256)");

    // ── 6. Write to temp file and replace ────────────────────────────────
    //
    // tempfile::NamedTempFile: creates a temporary file that is
    // automatically cleaned up on drop.
    //   https://docs.rs/tempfile/3/tempfile/struct.NamedTempFile.html
    //
    // self_replace::self_replace(): atomically replaces the running binary.
    //   Unix: rename(2) — atomic within the same filesystem.
    //   Windows: rename + FILE_FLAG_DELETE_ON_CLOSE helper process.
    //   https://docs.rs/self-replace/1/self_replace/fn.self_replace.html
    eprintln!();
    info("Updating apvm...");

    let mut temp_file = tempfile::NamedTempFile::new()
        .map_err(|e| Error::Update(format!("Failed to create temporary file: {e}")))?;

    temp_file.write_all(&binary_bytes).map_err(|e| {
        Error::Update(format!(
            "Failed to write downloaded binary to temp file: {e}"
        ))
    })?;

    // Set executable permission on Unix before replacement.
    // std::os::unix::fs::PermissionsExt:
    //   https://doc.rust-lang.org/std/os/unix/fs/trait.PermissionsExt.html
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        let perms = std::fs::Permissions::from_mode(0o755);
        std::fs::set_permissions(temp_file.path(), perms)
            .map_err(|e| Error::Update(format!("Failed to set executable permission: {e}")))?;
    }

    self_replace::self_replace(temp_file.path()).map_err(|e| {
        Error::Update(format!(
            "Failed to replace the binary: {e}\n\
             \n\
             This can happen if:\n\
             - The binary is in a read-only location\n\
             - You don't have write permission to the install directory\n\
             \n\
             Try running with elevated permissions, or download manually from:\n\
             https://github.com/{REPO_OWNER}/{REPO_NAME}/releases/latest"
        ))
    })?;

    success(&format!("Updated successfully: {current} → {latest}"));
    eprintln!();
    info("Restart your shell or run 'apvm --version' to verify.");

    Ok(())
}


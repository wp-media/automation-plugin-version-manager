/// Create a GitHub client for the update check.
///
/// Tries environment variables first (same precedence as the main CLI),
/// falls back to anonymous (rate-limited but sufficient for public repos).
///
/// # Sources
///
/// - `GITHUB_TOKEN` / `GH_TOKEN`: standard environment variables used by
///   GitHub CLI and most CI systems.
///   <https://docs.github.com/en/actions/security-for-github-actions/security-guides/automatic-token-authentication>
/// - [`apvm_core::git::resolve_github_token`]: existing token resolution logic.
async fn make_github_client() -> Result<GitHubClient> {
    let resolved = apvm_core::git::resolve_github_token(None).await;
    match resolved {
        Some(rt) => {
            tracing::debug!("Update: using GitHub token from {}", rt.source);
            GitHubClient::new(&rt.token)
        }
        None => {
            tracing::debug!("Update: no GitHub token found, using anonymous client");
            GitHubClient::anonymous()
        }
    }
}


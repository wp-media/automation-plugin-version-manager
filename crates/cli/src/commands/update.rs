/// Map the current platform to the release artifact name.
///
/// Artifact names must match those published by `.github/workflows/release-cli.yml`.
///
/// # Sources
///
/// - [`std::env::consts::OS`]: compile-time constant for the target OS.
///   <https://doc.rust-lang.org/std/env/consts/constant.OS.html>
/// - [`std::env::consts::ARCH`]: compile-time constant for the target architecture.
///   <https://doc.rust-lang.org/std/env/consts/constant.ARCH.html>
fn artifact_name() -> Result<&'static str> {
    match (std::env::consts::OS, std::env::consts::ARCH) {
        ("macos", "aarch64") => Ok("apvm-darwin-arm64"),
        ("macos", "x86_64") => Ok("apvm-darwin-x64"),
        ("linux", "x86_64") => Ok("apvm-linux-x64-gnu"),
        ("linux", "aarch64") => Ok("apvm-linux-arm64-gnu"),
        ("windows", "x86_64") => Ok("apvm-win32-x64-msvc.exe"),
        (os, arch) => Err(Error::Update(format!(
            "No pre-built binary available for {os}/{arch}.\n\
             APVM provides binaries for: macOS (arm64/x64), Linux (x64/arm64), Windows (x64).\n\
             \n\
             To update from source instead:\n\
               cargo install --path crates/cli"
        ))),
    }
}

// ─────────────────────────────────────────────────────────────────────────────
// Checksum parsing
// ─────────────────────────────────────────────────────────────────────────────

/// Extract the expected SHA-256 hash for a given artifact from `checksums.txt`.
///
/// The checksums file format is the standard `sha256sum` output:
/// ```text
/// <hex_hash>  <filename>
/// ```
///
/// Two spaces separate the hash from the filename (GNU coreutils convention).
/// Source: <https://man7.org/linux/man-pages/man1/sha256sum.1.html>
fn parse_checksum(checksums_text: &str, artifact: &str) -> Result<String> {
    for line in checksums_text.lines() {
        // sha256sum format: "<hash>  <filename>" (two spaces)
        // Also handle single space for robustness.
        let parts: Vec<&str> = line.splitn(2, ' ').collect();
        if parts.len() == 2 {
            let hash = parts[0].trim();
            // Strip a leading `*` produced by `sha256sum -b` (binary mode):
            // text mode:   `<hash>  <filename>`
            // binary mode: `<hash> *<filename>`
            // Source: https://man7.org/linux/man-pages/man1/sha256sum.1.html
            let filename = parts[1].trim().trim_start_matches('*');
            if filename == artifact {
                // Validate hash is 64 hex characters (SHA-256 = 256 bits = 64 hex chars)
                if hash.len() == 64 && hash.chars().all(|c| c.is_ascii_hexdigit()) {
                    return Ok(hash.to_lowercase());
                }
                return Err(Error::Update(format!(
                    "Invalid SHA-256 hash for '{artifact}' in checksums.txt: '{hash}'"
                )));
            }
        }
    }
    Err(Error::Update(format!(
        "No checksum found for '{artifact}' in checksums.txt.\n\
         This may indicate the release assets are incomplete."
    )))
}

// ─────────────────────────────────────────────────────────────────────────────
// Version parsing
// ─────────────────────────────────────────────────────────────────────────────

/// Extract the SemVer version string from a release tag name.
///
/// APVM release tags follow the pattern `cli/vX.Y.Z`. This strips the
/// `cli/v` prefix to get a parseable SemVer string.
///
/// Falls back to stripping just a `v` prefix for compatibility.
fn extract_version_from_tag(tag: &str) -> &str {
    tag.strip_prefix("cli/v")
        .or_else(|| tag.strip_prefix('v'))
        .unwrap_or(tag)
}

// ─────────────────────────────────────────────────────────────────────────────
// Asset lookup
// ─────────────────────────────────────────────────────────────────────────────

/// Find an asset by name within a release's assets list.
fn find_asset<'a>(release: &'a Release, name: &str) -> Result<&'a ReleaseAsset> {
    release
        .assets
        .iter()
        .find(|a| a.name == name)
        .ok_or_else(|| {
            let available = release
                .assets
                .iter()
                .map(|a| a.name.as_str())
                .collect::<Vec<_>>()
                .join(", ");
            Error::Update(format!(
                "Asset '{name}' not found in release '{}'.\nAvailable assets: {available}",
                release.tag_name
            ))
        })
}

/// Format a byte count as a human-readable string (KB or MB).
fn format_size(bytes: u64) -> String {
    if bytes >= 1_048_576 {
        format!("{:.1} MB", bytes as f64 / 1_048_576.0)
    } else {
        format!("{:.0} KB", bytes as f64 / 1024.0)
    }
}

